/**
 * Retorna a quantidade de pintinhos lida na balanca.
 *
 * IMPLEMENTACAO TEMPORARIA: valor randomico inteiro entre 0 e 100 (inclusive),
 * apenas para testes. Substituir pela leitura real da balanca.
 *
 * @returns {number} inteiro entre 0 e 100
 */
